#!/bin/bash
# Compile the project sources of the Unity-generated Xcode project (Classes/ and the plugins under Libraries/) to .o (run inside the build Linux).
# Usage: build_native.sh <repo> <out_dir> [vanilla|tuned] [only these file names...]
#   vanilla (default): Libraries/ holds the restored plugins from Assets/Plugins/iOS/, for per-function comparison with the original
#   tuned: additionally puts the ad, analytics and networking stubs from native_stubs/ into Libraries/
#   With file names given (e.g. NativeUtils.mm), only those files are compiled and other .o files in out_dir are kept, for single-file iteration
#   Environment variable REGISTER_MONO_MODULES=<RegisterMonoModules.cpp>: replaces the empty file of the same name in the template and compiles it
#   (produced by the generator in toolchain/register_mono_modules/ following Unity 3.5.7's logic)
#
# The original project's path on the build machine is /Applications/buildAgent/work/a03c2b4a5f58e0ef/GeneratedProject_ios;
# Xcode invokes clang with absolute paths, so __FILE__ strings and debug info contain this path; hence a project is set up at the same path here:
#   1. Classes/ and Libraries/ from the Unity 3.5.7 template
#   2. Copy Assets/Plugins/iOS/ following Unity 3.5.7 PostProcessiPhonePlayer.InstalliPhonePluginFiles:
#      Directory.GetFiles takes top-level files only (subdirectories are ignored); files whose names are in the reserved list kReservedFilenames
#      (e.g. AppController.mm) are copied to Classes/, replacing the template files of the same name; the rest are copied to Libraries/
# Compiler flags taken from the template's Release configuration (verified on the 71 functions in Classes/).
set -euo pipefail

# ---- Constants ----
TEMPLATE=/work/ckz2/unity357/PlaybackEngines/iPhonePlayer/iPhone-Trampoline
STAGE=/Applications/buildAgent/work/a03c2b4a5f58e0ef/GeneratedProject_ios
TOOLCHAIN=$(cd "$(dirname "$0")" && pwd)
XCODE45="$TOOLCHAIN/xcode45.sh"
SDK=/work/xcode45/Xcode.app/Contents/Developer/Platforms/iPhoneOS.platform/Developer/SDKs/iPhoneOS6.0.sdk
# -fvisibility=hidden: not in the template; it is Glu's project setting (GCC_SYMBOLS_PRIVATE_EXTERN = YES). It does not change instructions, so L1 cannot see it;
# evidence: all symbols in the original Classes/ and plugins are private extern (n_type 0x1e, even _main), and ObjC classes' class_ro carries
# RO_HIDDEN (0x10). Found by the post-link L2 / L3 comparison on 2026-11-18
COMMON_FLAGS="-arch armv7 -isysroot $SDK -miphoneos-version-min=5.1 -Os -mno-thumb -g -fvisibility=hidden -include Classes/iPhone_target_Prefix.pch -IClasses -ILibraries"
# Classes/ units linked into the original (the template also has RegisterClasses.cpp and iPhone_Profiler.cpp, which the original did not compile in)
CLASSES_SOURCES="AppController.mm iPhone_target2AppDelegate.m main.mm iPhone_GlesSupport.cpp"
# Files generated by Unity at build time: compiled only when REGISTER_MONO_MODULES is given
GENERATED_SOURCES="RegisterMonoModules.cpp"
REGISTER_MONO_MODULES=${REGISTER_MONO_MODULES:-}
# Unity 3.5.7 PostProcessiPhonePlayer.kReservedFilenames: files with these names in Plugins/iOS go to Classes/
RESERVED_FILENAMES="AppController.h AppController.mm MainWindow.xib RegisterClasses.cpp RegisterClasses.h iPhone_target2AppDelegate.h iPhone_target2AppDelegate.m main.mm iPhone_Common.h iPhone_Profiler.h iPhone_Profiler.cpp iPhone_GlesSupport.h iPhone_GlesSupport.cpp"

if [ $# -lt 2 ]; then
    echo "usage: build_native.sh <repo> <out_dir> [vanilla|tuned]" >&2
    exit 2
fi
repo=$(realpath "$1")
out_dir=$(realpath -m "$2")
flavor=${3:-vanilla}
only_files=""
if [ $# -gt 3 ]; then
    shift 3
    only_files=" $* "
fi

# ---- Set up the project ----
rm -rf "$STAGE"
mkdir -p "$STAGE"
cp -a "$TEMPLATE/Classes" "$TEMPLATE/Libraries" "$STAGE/"

# Install a plugin directory by Unity's rules: top-level files only; reserved file names go to Classes/, the rest to Libraries/
plugin_count=0
reserved_count=0
install_plugin_files() {
    local source=$1
    local file
    local name
    [ -d "$source" ] || return 0
    for file in "$source"/*; do
        [ -f "$file" ] || continue
        name=$(basename "$file")
        case "$name" in
            .*|*.md) continue ;;
        esac
        case " $RESERVED_FILENAMES " in
            *" $name "*)
                cp -a "$file" "$STAGE/Classes/"
                reserved_count=$((reserved_count + 1))
                ;;
            *)
                cp -a "$file" "$STAGE/Libraries/"
                plugin_count=$((plugin_count + 1))
                ;;
        esac
    done
}
install_plugin_files "$repo/Assets/Plugins/iOS"
if [ "$flavor" = "tuned" ]; then
    install_plugin_files "$repo/native_stubs"
fi
if [ -n "$REGISTER_MONO_MODULES" ]; then
    cp "$REGISTER_MONO_MODULES" "$STAGE/Libraries/RegisterMonoModules.cpp"
    GENERATED_SOURCES=""
fi
echo "staged $STAGE ($flavor): $plugin_count files -> Libraries/, $reserved_count reserved files -> Classes/"

# ---- Compile ----
# Template Release: GCC_ENABLE_CPP_EXCEPTIONS/RTTI/OBJC_EXCEPTIONS are all NO. Without -fno-objc-exceptions,
# functions with __block variables get extra SjLj exception cleanup code (observed in _SaveDataToFile of FileManagerImpl.mm)
language_flags() {
    case "$1" in
        *.mm) echo "-x objective-c++ -fno-exceptions -fno-rtti -fno-objc-exceptions" ;;
        *.m) echo "-x objective-c -std=c99 -fno-objc-exceptions" ;;
        *.cpp) echo "-x c++ -fno-exceptions -fno-rtti" ;;
        *.c) echo "-x c -std=c99" ;;
        *) echo "" ;;
    esac
}

compile_one() {
    local relative=$1
    local name
    name=$(basename "$relative")
    if [ -n "$only_files" ]; then
        case "$only_files" in
            *" $name "*) ;;
            *) return 0 ;;
        esac
    fi
    local object="$out_dir/${name%.*}.o"
    local flags
    flags=$(language_flags "$name")
    # shellcheck disable=SC2086
    if ! bash "$XCODE45" clang $flags $COMMON_FLAGS -c "$STAGE/$relative" -o "$object" 2> "$out_dir/${name%.*}.log"; then
        echo "FAILED $relative" >&2
        grep -E "error" "$out_dir/${name%.*}.log" | head -10 >&2
        return 1
    fi
    rm -f "$out_dir/${name%.*}.log"
}

if [ -z "$only_files" ]; then
    rm -rf "$out_dir"
fi
mkdir -p "$out_dir"
cd "$STAGE"
failed=0
for name in $CLASSES_SOURCES; do
    compile_one "Classes/$name" || failed=1
done
for path in Libraries/*.m Libraries/*.mm Libraries/*.cpp Libraries/*.c; do
    [ -f "$path" ] || continue
    name=$(basename "$path")
    case " $GENERATED_SOURCES " in
        *" $name "*) continue ;;
    esac
    compile_one "$path" || failed=1
done
count=$(find "$out_dir" -name '*.o' | wc -l)
echo "compiled $count objects -> $out_dir"
exit $failed
