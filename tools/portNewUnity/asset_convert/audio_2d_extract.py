"""Extract the sounds that Unity 3.5 imported as 2D and write them into a C# table.

In 3.5 a clip was 2D or 3D by its import setting ("3D Sound"), and AudioSource.panLevel only affected 3D clips.
Unity 6 has no per-clip flag: AudioSource.spatialBlend alone decides, and the API updater mapped panLevel straight to it.
So the GameData presets (PanLevel = 1) turn the original 2D sounds (UI, mission, power-ups, voice-over...) into
fully 3D sounds that are silent away from the listener. PcAudio uses this table to force those back to 2D.

Source: the AudioImporter "3D: 0/1" field in the .meta files of the untouched ULegacy export.
Output: <project root>/Source/Runtime/PcPort/PcAudio.Generated.cs

Usage: python audio_2d_extract.py <export root> <project root>
"""

import re
import sys
from pathlib import Path

SOUND_ROOT = Path("Assets/Resources/22khz")
OUTPUT_FILE = Path("Source/Runtime/PcPort/PcAudio.Generated.cs")
AUDIO_SUFFIXES = {".wav", ".mp3", ".ogg", ".aif", ".aiff"}
IMPORT_3D = re.compile(r"^\s*3D: (\d)\s*$", re.MULTILINE)


def read_is_3d(meta_path):
    """Returns the 3D flag of one AudioImporter .meta file."""
    text = meta_path.read_text(encoding="utf-8")
    match = IMPORT_3D.search(text)
    if match is None:
        raise ValueError(f"no '3D:' field in {meta_path}")
    return match.group(1) == "1"


def collect_2d_sounds(sound_root):
    """Sound names (path under 22khz, no extension, lower case) of every clip imported as 2D."""
    names_2d = []
    count_3d = 0
    for clip_path in sorted(sound_root.rglob("*")):
        if clip_path.suffix.lower() not in AUDIO_SUFFIXES:
            continue
        meta_path = clip_path.with_name(clip_path.name + ".meta")
        relative = clip_path.relative_to(sound_root).with_suffix("")
        name = relative.as_posix().lower()
        if read_is_3d(meta_path):
            count_3d += 1
        else:
            names_2d.append(name)
    print(f"[audio_2d_extract] clips: {len(names_2d)} 2D, {count_3d} 3D")
    return names_2d


def render_csharp(names_2d):
    """C# source of the generated partial class."""
    lines = [
        "// Generated by tools/portNewUnity/asset_convert/audio_2d_extract.py from the original import settings. Do not edit.",
        "using System.Collections.Generic;",
        "",
        "public static partial class PcAudio",
        "{",
        "\t/// <summary>Sounds imported as 2D in Unity 3.5 (name under 22Khz, lower case, no extension).</summary>",
        "\tprivate static readonly HashSet<string> Legacy2DSounds = new HashSet<string>",
        "\t{",
    ]
    for name in names_2d:
        lines.append(f'\t\t"{name}",')
    lines.append("\t};")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main():
    """Entry point."""
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(1)
    export_root = Path(sys.argv[1])
    project_root = Path(sys.argv[2])
    names_2d = collect_2d_sounds(export_root / SOUND_ROOT)
    output_path = project_root / OUTPUT_FILE
    output_path.write_text(render_csharp(names_2d), encoding="utf-8", newline="\n")
    print(f"[audio_2d_extract] wrote {output_path}")


if __name__ == "__main__":
    main()
